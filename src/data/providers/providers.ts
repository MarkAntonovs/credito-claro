export const FINAL_PROVIDER_PROFILE_SLUGS = ["lineru", "doctor-peso", "finteres"] as const;

export function getFinalProviderProfilePath(slug: string): string | null {
  return FINAL_PROVIDER_PROFILE_SLUGS.some((profileSlug) => profileSlug === slug)
    ? `/prestamistas/${slug}/`
    : null;
}

export const DIRECT_PROVIDERS = VERIFIED_PROVIDERS.filter(
  (provider) => provider.providerType === "direct_credit_provider",
);

export const INTERMEDIARY_PROVIDERS = VERIFIED_PROVIDERS.filter(
  (provider) =>
    provider.providerType === "broker" ||
    provider.providerType === "aggregator" ||
    provider.providerType === "lead_generator",
);

export const HOMEPAGE_PROVIDERS = VERIFIED_PROVIDERS.filter((provider) => provider.featured);

export const PROVIDERS_ALPHABETICAL = [...VERIFIED_PROVIDERS].sort((first, second) =>
  first.name.localeCompare(second.name, "es-CO", { sensitivity: "base" }),
);

export const ACTIVE_PROVIDERS = PROVIDERS_ALPHABETICAL.filter((provider) => provider.active);
export const INACTIVE_PROVIDERS = PROVIDERS_ALPHABETICAL.filter((provider) => !provider.active);

export function getProviderBySlug(slug: string): Provider | undefined {
  return VERIFIED_PROVIDERS.find((provider) => provider.slug === slug);
}
